"""Kaggle kernel packaging and CLI command builders.

``write_kernel_dir`` stages a pushable kernel directory: the Kaggle
``kernel-metadata.json`` descriptor plus a generated ``main.py`` driver that
pip-installs the repo at the pinned commit, then calls
``demand_forecast.kaggle.kernel_workload.run_workload`` on the mounted prepared
dataset and pretrained bundle and prints the ``WORKLOAD_OK`` marker. The
``push_argv``, ``status_argv``, ``output_argv``, ``parse_status``,
``check_status`` and ``check_push`` helpers compose and interpret the
``kaggle kernels`` commands the host runner executes; nothing here invokes a
process.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from pprint import pformat
from typing import Any

__all__ = [
    "check_push",
    "check_status",
    "output_argv",
    "parse_status",
    "push_argv",
    "status_argv",
    "write_kernel_dir",
]

_QUOTED_STATUS = re.compile(r'has status "([^"]+)"')
_ENUM_STATUS = re.compile(r"\bKernelWorkerStatus\.([A-Z_]+)\b")
_BARE_STATUS = re.compile(r"[A-Z_]+")
_FAILURE_MESSAGE = re.compile(r'Failure message: "([^"]*)"')
_PUSH_ERROR_PREFIX = "Kernel push error:"
_ERROR_WORD = "ERROR"
_CANCEL_PREFIX = "CANCEL"

_DRIVER_TEMPLATE = '''"""Kaggle kernel driver for {kernel_id}.

Generated by demand_forecast.kaggle.kernels — edit that module, never this file.
Installs the repo at the pinned commit, runs the full workload (zero-shot and
fine-tune, both windows) on the mounted datasets, and prints the WORKLOAD_OK
completion marker.
"""

import subprocess
import sys
from pathlib import Path

{install_line}

from demand_forecast.kaggle.kernel_workload import run_workload

WORKLOAD_KWARGS = {workload_kwargs}

for _key in ("prepared_root", "out_root", "init_from"):
    if _key in WORKLOAD_KWARGS:
        WORKLOAD_KWARGS[_key] = Path(WORKLOAD_KWARGS[_key])

run_workload(**WORKLOAD_KWARGS)
print("WORKLOAD_OK", flush=True)
'''


def _driver_source(kernel_id: str, repo_sha: str, workload_kwargs: dict[str, str]) -> str:
    """Render the kernel ``main.py`` for ``kernel_id``.

    The workload kwargs are embedded as a Python literal (all values are
    strings); the driver converts the three path values to ``Path`` and passes
    everything to ``run_workload`` as keyword arguments.
    """
    install_line = (
        'subprocess.check_call([sys.executable, "-m", "pip", "install", "--quiet", '
        f'"git+https://github.com/alessiosavi/demand-forecast@{repo_sha}"])'
    )
    return _DRIVER_TEMPLATE.format(
        kernel_id=kernel_id,
        install_line=install_line,
        workload_kwargs=pformat(workload_kwargs, indent=4, sort_dicts=False),
    )


def write_kernel_dir(
    directory: Path,
    *,
    kernel_id: str,
    title: str,
    prepared_dataset: str,
    assets_dataset: str,
    repo_sha: str,
    workload_kwargs: dict[str, str],
) -> Path:
    """Write ``kernel-metadata.json`` and ``main.py`` into ``directory``; return it.

    The metadata declares a private GPU script kernel with internet access and
    both datasets as sources. ``workload_kwargs`` is embedded in ``main.py``
    verbatim and passed to ``run_workload`` in the kernel: it carries the mount
    paths (``prepared_root``, ``out_root``, ``init_from``) and the optional
    ``bundle_identity``. A directory already registered to a different kernel id
    raises ``ValueError`` instead of being silently repointed.
    """
    directory = Path(directory)
    metadata_path = directory / "kernel-metadata.json"
    if metadata_path.exists():
        existing = json.loads(metadata_path.read_text(encoding="utf-8"))
        existing_id = existing.get("id")
        if existing_id != kernel_id:
            raise ValueError(
                f"kernel directory {directory} is registered to {existing_id!r}, not {kernel_id!r}"
            )
    metadata: dict[str, Any] = {
        "id": kernel_id,
        "title": title,
        "code_file": "main.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_tpu": False,
        "enable_internet": True,
        "machine_shape": "",
        "dataset_sources": [prepared_dataset, assets_dataset],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }
    directory.mkdir(parents=True, exist_ok=True)
    with metadata_path.open("w", encoding="utf-8") as stream:
        json.dump(metadata, stream, indent=2)
    (directory / "main.py").write_text(
        _driver_source(kernel_id, repo_sha, workload_kwargs), encoding="utf-8"
    )
    return directory


def push_argv(
    directory: Path, accelerator: str = "NvidiaTeslaT4", timeout_s: int = 21600
) -> list[str]:
    """Compose the ``kaggle kernels push`` argv for ``directory``."""
    return [
        "kaggle",
        "kernels",
        "push",
        "-p",
        str(directory),
        "--accelerator",
        accelerator,
        "-t",
        str(timeout_s),
    ]


def status_argv(kernel_id: str) -> list[str]:
    """Compose the ``kaggle kernels status`` argv for ``kernel_id``."""
    return ["kaggle", "kernels", "status", kernel_id]


def output_argv(kernel_id: str, dest: Path) -> list[str]:
    """Compose the ``kaggle kernels output`` argv downloading into ``dest``."""
    return ["kaggle", "kernels", "output", "-p", str(dest), kernel_id]


def parse_status(output: str) -> str:
    """Extract the raw status word from ``kaggle kernels status`` output.

    The CLI prints ``<kernel> has status "KernelWorkerStatus.<WORD>"``; the
    returned word is the verbatim ``<WORD>`` (``QUEUED``, ``RUNNING``,
    ``COMPLETE``, ``ERROR``, ``CANCEL_REQUESTED``, ``CANCEL_ACKNOWLEDGED``,
    ``NEW_SCRIPT``). A bare ``KernelWorkerStatus.<WORD>``
    token or a bare ``<WORD>`` string are accepted too; anything else raises
    ``ValueError`` rather than guessing.
    """
    for pattern in (_QUOTED_STATUS, _ENUM_STATUS):
        match = pattern.search(output)
        if match is not None:
            return match.group(1).removeprefix("KernelWorkerStatus.")
    stripped = output.strip()
    if _BARE_STATUS.fullmatch(stripped):
        return stripped
    raise ValueError(f"no kernel status word in output: {output!r}")


def check_status(returncode: int, output: str) -> None:
    """Raise ``RuntimeError`` when the status call or the kernel run failed.

    A non-zero CLI return code, the ``ERROR`` word and every ``CANCEL*`` word
    (``CANCEL_REQUESTED``, ``CANCEL_ACKNOWLEDGED``) are failures; ``QUEUED``,
    ``RUNNING`` and ``COMPLETE`` pass so the caller's poll loop decides when to
    stop. The CLI's failure message, when present, is included in the error.
    """
    if returncode != 0:
        raise RuntimeError(
            f"kaggle kernels status failed with exit code {returncode}: {output.strip()}"
        )
    word = parse_status(output)
    if word == _ERROR_WORD or word.startswith(_CANCEL_PREFIX):
        match = _FAILURE_MESSAGE.search(output)
        detail = "" if match is None else f": {match.group(1)}"
        raise RuntimeError(f"kaggle kernel run failed with status {word}{detail}")


def check_push(output: str) -> None:
    """Raise ``RuntimeError`` when the CLI reported a rejected kernel push.

    ``kaggle kernels push`` prints the server's rejection to stdout and still
    exits 0 (e.g. the concurrent-GPU-session cap), so the exit code alone does
    not tell a push from a rejection; the marker line does.
    """
    for line in output.splitlines():
        if line.startswith(_PUSH_ERROR_PREFIX):
            raise RuntimeError(line.strip())
