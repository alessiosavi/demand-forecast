FILTER_NAMES = ("all_nan", "min_points", "constant", "duplicate", "subsample")
SYNTHETIC_NOTICE = (
    "generated by Amazon's Chronos authors from 28 public datasets; no explicit licence "
    "on the dataset card; used under research terms"
)


def select_sources(config: CorpusBuildConfig, names: Sequence[str] = ()) -> list[BuildSource]:
    """Select whole sources and fix their deduplication precedence by name."""
    unknown = set(names) - {source.name for source in config.sources}
    if unknown:
        raise ValueError(f"unknown sources: {sorted(unknown)}")
    return sorted((s for s in config.sources if not names or s.name in names), key=lambda s: s.name)


def source_files(source: BuildSource) -> list[dict]:
    """List included paths and byte sizes without downloading data."""
    patterns = source.allow_patterns()
    if source.local_path is not None:
        if not source.local_path.is_dir():
            raise FileNotFoundError(source.local_path)
        files = (
            {"path": p.relative_to(source.local_path).as_posix(), "size": p.stat().st_size}
            for entry in source.include
            for p in (source.local_path / entry.name).rglob("*")
            if p.is_file()
        )
    else:
        from huggingface_hub import HfApi

        files = (
            {"path": f.path, "size": f.size}
            for f in HfApi().list_repo_tree(
                source.repo, repo_type="dataset", revision=source.revision, recursive=True
            )
            if hasattr(f, "size")
        )
    return sorted(
        (f for f in files if any(fnmatchcase(f["path"], p) for p in patterns)),
        key=lambda f: f["path"],
    )


def _download(source: BuildSource, root: Path) -> tuple[Path, list[dict]]:
    files = source_files(source)
    if source.local_path is not None:
        return source.local_path, files
    from huggingface_hub import snapshot_download

    destination = root / "downloads" / source.name
    snapshot_download(
        repo_id=source.repo,
        repo_type="dataset",
        revision=source.revision,
        allow_patterns=source.allow_patterns(),
        local_dir=destination,
    )
    return destination, files


def _rows(
    source: BuildSource, entry: CorpusEntry, directory: Path, inventory: list[dict]
) -> Iterator[dict]:
    if source.kind == "chronos_real":
        import pyarrow.parquet as pq

        # snapshot_download does not remove files left by another revision.
        files = [
            directory / f["path"] for f in inventory if Path(f["path"]).parent == Path(entry.name)
        ]
        if not files:
            raise FileNotFoundError(f"no parquet files in {directory / entry.name}")
        for path in files:
            with pq.ParquetFile(path) as parquet:
                # One row can already contain a long history; never batch entire folders.
                for batch in parquet.iter_batches(
                    batch_size=1, columns=["id", "timestamp", entry.target_column]
                ):
                    row = batch.to_pylist()[0]
                    timestamps = pd.DatetimeIndex(row["timestamp"]).as_unit("ns")
                    series_id = f"{source.name}/{entry.name}/{row['id']}"
                    if not timestamps.is_monotonic_increasing:
                        raise ValueError(f"non-monotonic timestamps for {series_id}")
                    freq = pd.infer_freq(timestamps) if len(timestamps) >= 3 else None
                    freq_fallback = freq is None and len(timestamps) >= 2
                    if freq_fallback:
                        deltas = np.diff(timestamps.asi8)
                        positive, counts = np.unique(deltas[deltas > 0], return_counts=True)
                        if not len(positive):
                            raise ValueError(f"no positive timestamp delta for {series_id}")
                        # np.unique sorts deltas, so argmax breaks ties toward the smallest.
                        delta = int(positive[counts.argmax()])
                        freq = pd.tseries.frequencies.to_offset(
                            pd.Timedelta(delta, unit="ns")
                        ).freqstr
                    yield dict(
                        item_id=row["id"],
                        target=row[entry.target_column],
                        start=timestamps[0] if len(timestamps) else None,
                        freq=freq,
                        freq_fallback=freq_fallback,
                        timestamp_count=len(timestamps),
                    )
    else:
        from datasets import load_from_disk

        dataset = load_from_disk(str(directory / entry.name))
        dataset.set_format("numpy", columns=["item_id", "start", "freq", "target"])
        yield from dataset


def _spool_folder(
    db: sqlite3.Connection,
    source: BuildSource,
    entry: CorpusEntry,
    directory: Path,
    inventory: list[dict],
) -> int:
    """External sort by item ID and numeric component; SQLite stores the values."""
    freq_fallback = 0
    db.execute("DROP TABLE IF EXISTS candidates")
    db.execute(
        "CREATE TABLE candidates (item TEXT, dim INTEGER, id TEXT UNIQUE, target BLOB, "
        "start INTEGER, freq TEXT, priority TEXT, PRIMARY KEY (item, dim))"
    )
    for row in _rows(source, entry, directory, inventory):
        raw = row["target"]
        if raw is None or row["item_id"] is None:
            raise ValueError(f"null item ID or target in {source.name}/{entry.name}")
        multivariate = len(raw) > 0 and isinstance(raw[0], (list, tuple, np.ndarray))
        components = enumerate(raw) if multivariate else [(-1, raw)]
        raw_start = row["start"]
        if isinstance(raw_start, np.ndarray):
            raw_start = raw_start[()]
        start = pd.Timestamp(raw_start)
        start_ns = None if pd.isna(start) else start.value
        freq = str(row["freq"]) if row.get("freq") is not None else None
        for dim, component in components:
            values = np.asarray(component, dtype="<f4").copy()
            if values.ndim != 1:
                raise ValueError(f"target must be one-dimensional per component: {entry.name}")
            if "timestamp_count" in row and row["timestamp_count"] != len(values):
                raise ValueError(f"timestamps do not align with target: {entry.name}")
            # Explicit bits make every NaN payload/sign identical on every platform.
            values.view("<u4")[np.isnan(values)] = 0x7FC00000
            item = str(row["item_id"])
            series_id = f"{source.name}/{entry.name}/{item}"
            if multivariate:
                series_id += f"/{dim}"
            priority = hashlib.sha256(f"{entry.name}\0{item}\0{dim}".encode()).hexdigest()
            try:
                db.execute(
                    "INSERT INTO candidates VALUES (?, ?, ?, ?, ?, ?, ?)",
                    (item, dim, series_id, values.tobytes(), start_ns, freq, priority),
                )
            except sqlite3.IntegrityError as exc:
                raise ValueError(f"duplicate source item/component ID: {series_id}") from exc
            freq_fallback += int(row.get("freq_fallback", False))
    db.commit()
    return freq_fallback


class _ShardWriter:
    """Bound an uncompressed row buffer and enforce actual parquet byte limits."""

    def __init__(self, directory: Path, limits: ShardLimits):
        import pyarrow as pa

        self.schema = pa.schema(
            [
                ("id", pa.string()),
                ("target", pa.list_(pa.float32())),
                ("start", pa.timestamp("ns")),
                ("freq", pa.string()),
                ("source", pa.string()),
                ("folder", pa.string()),
            ]
        )
        self.directory, self.limits = directory, limits
        directory.mkdir(parents=True, exist_ok=True)
        self.rows, self.bytes, self.count = [], 0, 0

    def append(self, row: dict) -> None:
        size = (
            row["target"].nbytes
            + sum(len(row[k].encode()) for k in ("id", "freq", "source", "folder"))
            + 64
        )
        if self.rows and (
            len(self.rows) >= self.limits.max_series or self.bytes + size > self.limits.max_bytes
        ):
            self.flush()
        self.rows.append(row)
        self.bytes += size

    def _write(self, rows: list[dict]) -> None:
        import pyarrow as pa
        import pyarrow.parquet as pq

        buffer = pa.BufferOutputStream()
        pq.write_table(
            pa.Table.from_pylist(rows, schema=self.schema),
            buffer,
            compression="zstd",
            compression_level=3,
            row_group_size=1024,
            version="2.6",
            data_page_version="1.0",
            use_dictionary=False,
            write_statistics=True,
            data_page_size=1048576,
            write_batch_size=1024,
        )
        data = buffer.getvalue()
        if len(data) > self.limits.max_bytes:
            if len(rows) == 1:
                raise ValueError(f"one series exceeds shards.max_bytes: {rows[0]['id']}")
            midpoint = len(rows) // 2
            self._write(rows[:midpoint])
            self._write(rows[midpoint:])
            return
        if self.count >= 99999:
            raise ValueError("more than 99999 shards; increase shard limits")
        (self.directory / f"part-{self.count:05d}.parquet").write_bytes(data.to_pybytes())
        self.count += 1

    def flush(self) -> None:
        if self.rows:
            self._write(self.rows)
            self.rows, self.bytes = [], 0

    def finish(self) -> None:
        self.flush()
        for i in range(self.count):
            (self.directory / f"part-{i:05d}.parquet").rename(
                self.directory / f"train-{i:05d}-of-{self.count:05d}.parquet"
            )


def _convert_folder(db, source, entry, directory, inventory, config, writer, duplicates) -> dict:
    freq_fallback = _spool_folder(db, source, entry, directory, inventory)
    report = entry.model_dump(mode="json", exclude_none=True) | dict(
        series_seen=0,
        series_kept=0,
        points_kept=0,
        finite_points_kept=0,
        freq_fallback=freq_fallback,
        dropped={k: 0 for k in FILTER_NAMES},
        duplicate_pairs_count=0,
    )
    db.execute("DROP TABLE IF EXISTS eligible")
    db.execute("CREATE TABLE eligible (item TEXT, dim INTEGER, priority TEXT)")
    for item, dim, series_id, blob, start, freq, priority in db.execute(
        "SELECT * FROM candidates ORDER BY item, dim"
    ):
        report["series_seen"] += 1
        values = np.frombuffer(blob, dtype="<f4")
        finite = values[np.isfinite(values)]
        dropped = None
        if config.filters.drop_all_nan and np.isnan(values).all():
            dropped = "all_nan"
        elif len(finite) < config.filters.min_points:
            dropped = "min_points"
        elif config.filters.drop_constant and np.all(finite == finite[0]):
            dropped = "constant"
        if dropped is not None:
            report["dropped"][dropped] += 1
            continue
        digest = hashlib.sha256(blob).digest()
        previous = db.execute("SELECT id FROM seen WHERE hash = ?", (digest,)).fetchone()
        if previous is not None:
            report["dropped"]["duplicate"] += 1
            report["duplicate_pairs_count"] += 1
            duplicates.write(json.dumps(dict(kept_id=previous[0], dropped_id=series_id)) + "\n")
            continue
        if start is None or not freq:
            raise ValueError(f"cannot infer source start/frequency for {series_id}")
        db.execute("INSERT INTO seen VALUES (?, ?)", (digest, series_id))
        db.execute("INSERT INTO eligible VALUES (?, ?, ?)", (item, dim, priority))
    cap = config.filters.max_series_per_folder
    if cap is not None:
        count = db.execute("SELECT COUNT(*) FROM eligible").fetchone()[0]
        report["dropped"]["subsample"] = max(0, count - cap)
        db.execute(
            "DELETE FROM eligible WHERE rowid NOT IN "
            "(SELECT rowid FROM eligible ORDER BY priority, item, dim LIMIT ?)",
            (cap,),
        )
    for series_id, blob, start, freq in db.execute(
        "SELECT c.id, c.target, c.start, c.freq FROM candidates c "
        "JOIN eligible e ON c.item = e.item AND c.dim = e.dim ORDER BY c.item, c.dim"
    ):
        values = np.frombuffer(blob, dtype="<f4")
        writer.append(
            dict(
                id=series_id,
                target=values,
                start=pd.Timestamp(start),
                freq=freq,
                source=source.name,
                folder=entry.name,
            )
        )
        report["series_kept"] += 1
        report["points_kept"] += len(values)
        report["finite_points_kept"] += int(np.isfinite(values).sum())
    db.commit()
    return report


def _totals(folders: list[dict]) -> dict:
    return {
        **{
            key: sum(f[key] for f in folders)
            for key in (
                "series_seen",
                "series_kept",
                "points_kept",
                "finite_points_kept",
                "freq_fallback",
                "duplicate_pairs_count",
            )
        },
        "dropped": {key: sum(f["dropped"][key] for f in folders) for key in FILTER_NAMES},
    }


def _notice(report: dict) -> str:
    lines = [
        "# Corpus v2 NOTICE",
        "",
        "commercial_use: false",
        "",
        "This is a research release. GiftEvalPretrain's dataset card restricts its bundle "
        "to research use. Original-source licence buckets do not override that restriction.",
        "",
        "## TSMixup / KernelSynth",
        "",
        SYNTHETIC_NOTICE + ".",
        "",
        "The 28-dataset derivation refers to TSMixup; KernelSynth uses Gaussian-process "
        "samples. Neither downloaded synthetic corpus has an explicit licence on the card.",
        "",
    ]
    for source in report["sources"]:
        lines += [
            f"## {source['name']}",
            "",
            f"Repository: {source['repo']} @ {source['revision']}",
            "",
        ]
        if source["bundle_terms"]:
            lines += [f"Bundle terms: {source['bundle_terms']}", ""]
        for folder in source["folders"]:
            name = folder.get("config", folder.get("folder"))
            lines += [
                f"### {name}",
                "",
                folder["attribution"],
                "",
                f"Licence: {folder['licence']} (bucket: {folder['bucket']}).",
                "",
            ]
            if folder.get("card_licence"):
                lines += [
                    f"Collection card label: {folder['card_licence']}; original-source terms above apply.",
                    "",
                ]
            lines += [f"Source: {folder['url']}", ""]
            if folder.get("licence_url"):
                lines += [f"Licence / evidence: {folder['licence_url']}", ""]
    return "\n".join(lines)


def build_corpus(
    config_path: Path, root: Path, *, names: Sequence[str] = (), keep_downloads: bool = False
) -> dict:
    """Build a complete selected-source corpus, preserving legacy synthetic shards.

    Selected sources define the whole new corpus. Refuse to mix a subset build
    with existing unselected kinds: cross-kind deduplication requires one build.
    Use a separate root for subsets. Failed conversion leaves published shards
    untouched. Publication itself requires exclusive access to the corpus root.
    """
    import pyarrow as pa

    config_path, root = Path(config_path), Path(root).resolve()
    config = CorpusBuildConfig.from_yaml(config_path)
    sources = select_sources(config, names)
    selected_kinds = {source.kind for source in sources}
    for kind in {"chronos_real", "gifteval_pretrain"} - selected_kinds:
        if (root / CORPUS_KINDS[kind]).exists():
            raise ValueError(
                "existing unselected kind: build all new kinds together or use a fresh root"
            )
    root.mkdir(parents=True, exist_ok=True)
    report = dict(
        version=2,
        commercial_use=config.commercial_use,
        build_tool_version=__version__,
        pandas_version=pd.__version__,
        pyarrow_version=pa.__version__,
        config_sha256=_sha256(config_path),
        sources=[],
        filters=config.filters.model_dump(),
        shards=config.shards.model_dump(),
        duplicate_pairs_file="duplicates.jsonl",
        synthetic_notice=SYNTHETIC_NOTICE,
    )
    with TemporaryDirectory(prefix=".corpus-build-", dir=root) as staging:
        stage = Path(staging)
        with (
            closing(sqlite3.connect(stage / "sort.sqlite")) as db,
            (stage / "duplicates.jsonl").open("w", encoding="utf-8") as duplicates,
        ):
            db.execute("PRAGMA temp_store = FILE")
            db.execute("PRAGMA cache_size = -8192")
            db.execute("CREATE TABLE seen (hash BLOB PRIMARY KEY, id TEXT)")
            for source in sources:
                directory, inventory = _download(source, root)
                writer = _ShardWriter(stage / CORPUS_KINDS[source.kind], config.shards)
                folders = [
                    _convert_folder(
                        db, source, entry, directory, inventory, config, writer, duplicates
                    )
                    for entry in sorted(source.include, key=lambda e: e.name)
                ]
                writer.finish()
                report["sources"].append(
                    dict(
                        name=source.name,
                        repo=source.repo,
                        revision=source.revision,
                        kind=source.kind,
                        bundle_terms=source.bundle_terms,
                        input_mode="local" if source.local_path else "hub",
                        input_bytes=sum(f["size"] for f in inventory),
                        folders=folders,
                        totals=_totals(folders),
                    )
                )
        report["totals"] = _totals([f for s in report["sources"] for f in s["folders"]])
        # Publish only after every source converts successfully. Old legacy dirs are never touched.
        for source in sources:
            destination = root / CORPUS_KINDS[source.kind]
            if destination.exists():
                shutil.rmtree(destination)
            destination.parent.mkdir(parents=True, exist_ok=True)
            (stage / CORPUS_KINDS[source.kind]).rename(destination)
        (stage / "duplicates.jsonl").replace(root / "duplicates.jsonl")
        write_manifest(corpus_manifest(root), root / "manifest.json")
        (root / "corpus.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        (root / "NOTICE-corpus.md").write_text(_notice(report), encoding="utf-8")
    if not keep_downloads:
        for source in sources:
            if source.local_path is None:
                shutil.rmtree(root / "downloads" / source.name)
    return report
